#!/usr/bin/env node
/**
 * Generate the CLEAN-PAIR fixture class.
 *
 * WHY THIS CLASS EXISTS. Registration 1377 was rejected with the node's own
 * numbers: our margin 0.8775, the champion's 0.9919, wins 14/15 vs 15/15. Our
 * offline corpus had predicted the champion at 0.438 — understating them 2.3x —
 * because every class in it is adversarial (parrots, entity swaps, refusals),
 * i.e. exactly the cases a lexical incumbent fails. The node's benchmark is not
 * that. It is CLEAN good-vs-bad pairs, where a lexically generous scorer is
 * near-perfect. This class mirrors what the node actually tests, so the harness
 * stops flattering us.
 *
 * HONESTY (FIXTURES.md, "generated by script from a fact schema, not hand-typed
 * against a visible ground truth"). Nothing here is authored against a ground
 * truth. Every answer is a MECHANICAL transform of text that already exists:
 *
 *   correct-verbatim   normalise(ground_truth)                 — markdown stripped
 *   correct-reworded   verbatim + a fixed connective table applied. The table
 *                      touches only verbs and function words ("is located in" ->
 *                      "resolves to"); it can never rewrite an entity or a figure.
 *   correct-terse      verbatim with a fixed stopword/hedge list deleted. Keeps
 *                      every entity, figure and identifier, in order.
 *   correct-verbose    a fixed preamble + verbatim + a fixed fact-free caveat.
 *   wrong-unrelated    the normalised ground truth of the NEXT record in the same
 *                      intent. Clearly wrong, and written by nobody for this row.
 *   wrong-swapped      verbatim with its proper-noun runs and figures replaced,
 *                      positionally, by the donor record's. Same prose skeleton,
 *                      every decisive fact false.
 *
 * Usage: node gen-clean-pairs.mjs
 */
import { readFile, writeFile } from "node:fs/promises";

const FIX = "C:/Users/hyada/OneDrive/Documents/Work-Related/Hackathons/Telegraph/track2/fixtures";
const INTENTS = ["IP_GEOLOCATION", "STORM_ALERT"];

// --- mechanical transforms -------------------------------------------------

/** Strip markdown and collapse whitespace. No content is added or removed. */
function normalise(text) {
  return text
    .replace(/\r/g, "")
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/[*_`#>]/g, "")
    .replace(/^\s*[-+]\s+/gm, "")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Connectives only. Every left-hand side is a verb phrase or a function word, so
 * no substitution can reach an entity, a figure or an identifier.
 */
const CONNECTIVES = [
  [/\bis located in\b/gi, "resolves to"],
  [/\bis situated in\b/gi, "sits in"],
  [/\bresolves to\b/gi, "maps to"],
  [/\bis announced by\b/gi, "is advertised by"],
  [/\bannounced by\b/gi, "advertised by"],
  [/\bis operated by\b/gi, "is run by"],
  [/\boperated by\b/gi, "run by"],
  [/\bis associated with\b/gi, "belongs to"],
  [/\bapproximately\b/gi, "about"],
  [/\bapproximate\b/gi, "rough"],
  [/\bindicates?\b/gi, "shows"],
  [/\breaches\b/gi, "gets up to"],
  [/\bis expected to\b/gi, "will"],
  [/\bare expected to\b/gi, "will"],
  [/\bwith peak\b/gi, "with maximum"],
  [/\bsustained\b/gi, "steady"],
  [/\bThe IP address\b/g, "The address"],
  [/\bIn summary,\s*/gi, ""],
];

function reword(text) {
  let out = text;
  for (const [re, to] of CONNECTIVES) out = out.replace(re, to);
  return out.replace(/\s+/g, " ").trim();
}

/** A fixed filler list. Deleting it keeps every decisive token, in order. */
const FILLER = new RegExp(
  "\\b(?:the|a|an|is|are|was|were|be|been|being|that|which|this|these|those|there|it|its|" +
    "of|to|in|on|at|by|for|with|from|as|and|or|but|also|very|quite|typically|generally|" +
    "commonly|currently|approximately|about|please|note|however|therefore|thus|so|" +
    "used|using|has|have|had|do|does|did|can|could|may|might|will|would|should)\\b",
  "gi",
);

function terse(text) {
  return text
    .replace(FILLER, " ")
    .replace(/\s*,\s*,+/g, ", ")
    .replace(/\s+([,.;:])/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
}

const PREAMBLE = "According to the record that was retrieved, ";
const CAVEAT =
  " These figures come from the provider's own dataset and are reproduced here without " +
  "further adjustment; readers who need a second opinion should consult the authoritative " +
  "registry directly rather than relying on this summary alone.";

function verbose(text) {
  // Do not lowercase a leading "I" -- "According to the record ..., i cannot"
  // is an artefact, not a phrasing a miner would produce.
  const head = /^I\b/.test(text) ? text : text.charAt(0).toLowerCase() + text.slice(1);
  return PREAMBLE + head + CAVEAT;
}

/**
 * A ground truth that refuses is a REFUSAL fixture, not a clean pair: there is
 * no "clearly correct" answer to pair against a "clearly wrong" one when the
 * truth itself declines to state a fact. Those rows are already covered by the
 * REFUSAL class and would only add noise here.
 */
const REFUSAL_GT = /\b(?:I cannot|I can't|I am unable|I'm unable|I do not have|I don't have|unable to provide|cannot provide the specific|no data (?:is )?available)\b/i;

// --- entity / figure substitution ------------------------------------------

const PROPER = /\b[A-Z][A-Za-z.'-]*(?:\s+[A-Z][A-Za-z.'-]*)*\b/g;
const FIGURE = /-?\d[\d,]*(?:\.\d+)?/g;
const SENTENCE_HEAD = /(^|[.!?]\s+)$/;

function extractProper(text) {
  const found = [];
  let m;
  PROPER.lastIndex = 0;
  while ((m = PROPER.exec(text)) !== null) {
    // Sentence-initial capitals are grammar, not entities.
    if (SENTENCE_HEAD.test(text.slice(0, m.index))) continue;
    found.push(m[0]);
  }
  return [...new Set(found)];
}

/**
 * Same prose, every decisive fact false: proper-noun runs and figures are
 * replaced positionally by the donor's. Nothing is invented.
 */
function swapFacts(text, donor) {
  const mine = extractProper(text);
  const theirs = extractProper(donor);
  let out = text;
  if (theirs.length > 0) {
    mine.forEach((name, i) => {
      const replacement = theirs[i % theirs.length];
      if (replacement.toLowerCase() === name.toLowerCase()) return;
      out = out.split(name).join(replacement);
    });
  }
  const donorFigures = donor.match(FIGURE) ?? [];
  if (donorFigures.length > 0) {
    let n = 0;
    out = out.replace(FIGURE, (fig) => {
      const replacement = donorFigures[n % donorFigures.length];
      n += 1;
      return replacement === fig ? String(Number(fig.replace(/,/g, "")) + 37) : replacement;
    });
  }
  return out;
}

// --- build -----------------------------------------------------------------

async function sourceRows(intent) {
  const rows = [];
  const seen = new Set();
  for (const set of ["real", "synth"]) {
    const body = JSON.parse(await readFile(`${FIX}/${set}/${intent}.json`, "utf8"));
    for (const fx of body.fixtures) {
      const gt = normalise(fx.ground_truth);
      const key = `${fx.question}\u0000${gt}`;
      // The synth corpus reuses a question across classes; one CLEAN-PAIR each.
      if (seen.has(key) || gt.length < 40 || REFUSAL_GT.test(gt)) continue;
      seen.add(key);
      rows.push({ question: fx.question.replace(/\s+/g, " ").trim(), gt, from: `${set}/${fx.id}` });
    }
  }
  return rows;
}

for (const intent of INTENTS) {
  const rows = await sourceRows(intent);
  // The donor is the LEXICALLY MOST DISTANT other record, not simply the next
  // one. Several recorded ground truths in this corpus say near-identical things
  // (three of them explain that a reserved IP range has no location), so "the
  // next record" would have produced a "wrong" answer that is substantially
  // right — a pair the class could only get credit for by accident.
  const bag = (t) => new Set(t.toLowerCase().match(/[a-z0-9.]+/g) ?? []);
  const bags = rows.map((r) => bag(r.gt));
  const jaccard = (a, b) => {
    let inter = 0;
    for (const w of a) if (b.has(w)) inter += 1;
    return inter / (a.size + b.size - inter || 1);
  };
  const fixtures = rows.map((row, i) => {
    let pick = (i + 1) % rows.length;
    for (let j = 0; j < rows.length; j += 1) {
      if (j !== i && jaccard(bags[i], bags[j]) < jaccard(bags[i], bags[pick])) pick = j;
    }
    const donor = rows[pick].gt;
    const v = row.gt;
    const swapped = swapFacts(v, donor);
    // Only keep the swapped variant when the substitution actually falsified
    // something: at least two distinct decisive tokens must have changed.
    const decisive = (t) => new Set([...extractProper(t), ...(t.match(FIGURE) ?? [])]);
    const before = decisive(v);
    let changed = 0;
    for (const d of before) if (!decisive(swapped).has(d)) changed += 1;
    const swapIsReal = changed >= 2;
    const answers = [
      { id: "correct-verbatim", text: v, quality: 1, note: "the ground truth as the miner would state it, markdown stripped" },
      { id: "correct-reworded", text: reword(v), quality: 1, note: "connective substitution only; no entity or figure touched" },
      { id: "correct-terse", text: terse(v), quality: 1, note: "fixed filler list deleted; every decisive token kept, in order" },
      { id: "correct-verbose", text: verbose(v), quality: 1, note: "fixed preamble and fact-free caveat wrapped around the verbatim form" },
      { id: "wrong-unrelated", text: donor, quality: 0, note: "the next record's ground truth: a real answer to a different question" },
      { id: "wrong-swapped", text: swapped, quality: 0, note: "same prose skeleton, entities and figures replaced positionally by the donor's" },
    ].filter((a) => a.text && a.text.length > 0 && !(a.id === "wrong-swapped" && !swapIsReal));

    const good = answers.filter((a) => a.quality === 1).map((a) => a.id);
    const bad = answers.filter((a) => a.quality === 0).map((a) => a.id);
    const pairs = [];
    for (const g of good) for (const b of bad) pairs.push([g, b]);

    return {
      id: `${intent.toLowerCase()}-cleanpair-${String(i + 1).padStart(2, "0")}`,
      intent,
      class: "CLEAN-PAIR",
      rationale:
        "mirrors the node's own benchmark shape: one clearly-correct answer in four phrasings " +
        "against one clearly-wrong answer. The adversarial classes measured the incumbent at " +
        "margin 0.438 where the node measured 0.992 (rejection of registration 1377), because " +
        "a lexically generous scorer only fails on pathologies. This class is where the gate " +
        "actually lives, and where a precision term that charges a correct answer for its own " +
        "wording costs us the ordering.",
      question: row.question,
      ground_truth: row.gt,
      answers,
      pairs,
      constraints: [
        {
          type: "near_equal",
          ids: good,
          tolerance: 0.05,
          note: "every phrasing of the same correct answer must score alike; the reworded/verbose gap was the measured defect",
        },
      ],
      provenance: {
        source: "synthetic",
        derived_from: row.from,
        method: "mechanical transform of existing fixture text (gen-clean-pairs.mjs); no answer authored against a ground truth",
        captured: "2026-08-27",
      },
    };
  });

  const path = `${FIX}/synth/${intent}_CLEAN_PAIR.json`;
  await writeFile(path, JSON.stringify({ fixtures }, null, 1) + "\n");
  console.log(`${path}: ${fixtures.length} fixtures, ${fixtures.reduce((n, f) => n + f.pairs.length, 0)} pairs`);
}
